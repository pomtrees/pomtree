// Static vendor assets for the /ui terminal (xterm.js and addons): a fixed whitelist read from observe's
// vendor directory. Anything outside the whitelist is a 404, so no path from the URL ever reaches the fs.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { INBOX_JS, INBOX_SCRIPT_URL, vendorDir } from "@pomtree/observe";

export const VENDOR_URL_PREFIX = "/ui/vendor/";

const TYPES: Readonly<Record<string, string>> = {
  "xterm.js": "text/javascript; charset=utf-8",
  "xterm.css": "text/css; charset=utf-8",
  "addon-fit.js": "text/javascript; charset=utf-8",
  "addon-webgl.js": "text/javascript; charset=utf-8",
};

/** The file for `/ui/vendor/<name>` or null (not whitelisted, or missing on disk). */
export function readVendorAsset(pathname: string, dir: string = vendorDir()): { body: Buffer; contentType: string } | null {
  if (!pathname.startsWith(VENDOR_URL_PREFIX)) return null;
  const name = pathname.slice(VENDOR_URL_PREFIX.length);
  const contentType = Object.hasOwn(TYPES, name) ? TYPES[name] : undefined;
  if (!contentType) return null;
  try {
    return { body: readFileSync(join(dir, name)), contentType };
  } catch {
    return null;
  }
}

/** The Inbox pane's script for `/ui/inbox.js` (generated by observe, so it is always in step with the pane markup), else null. */
export function readInboxScript(pathname: string): { body: string; contentType: string } | null {
  return pathname === INBOX_SCRIPT_URL ? { body: INBOX_JS, contentType: "application/javascript; charset=utf-8" } : null;
}
