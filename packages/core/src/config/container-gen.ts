// Generates container-contract.gen.ts, the one module every shipped in-image directory carries (the image layout is flat COPYs,
// so a relative import resolves only inside one copied set). It holds the contract digest, the image facts, the delivered keys'
// bounds and defaults, and the reader (container-reader.ts, verbatim). Pure: the caller passes the reader's source text
// (read from CONTAINER_READER_SOURCE_PATH). packages/core/scripts/gen-config.ts writes every copy; a test in core and one in each
// owning package regenerates the text and compares. The output is laid out as Biome formats it, so `pnpm format:check` passes.
import { join } from "node:path";
import { CONTAINER_CONFIG_ENV, CONTAINER_CONFIG_MAX_BYTES, IMAGE_FACTS, containerContract, containerDefaults, containerParams } from "./container.ts";
import type { ConfigRegistry } from "./registry.ts";

// Repo-relative paths of the generated copies, each shipped by the agent image COPY of its directory.
export const SHIPPED_CONTRACT_COPIES = [
  "packages/agent-image/src/container-contract.gen.ts",
  "packages/agent-image/ext/pomtree-browser/container-contract.gen.ts",
  "packages/pomtree/src/container-contract.gen.ts",
  "packages/sandbox-docker/src/container-contract.gen.ts",
] as const;

// The absolute path of the reader source the generated module embeds.
export const CONTAINER_READER_SOURCE_PATH = join(import.meta.dirname, "container-reader.ts");

const LINE_WIDTH = 160;
const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (k: string): string => (IDENT_RE.test(k) ? k : JSON.stringify(k));

// A TypeScript literal on one line, in Biome's spacing.
function literal(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map(literal).join(", ")}]`;
  if (typeof v === "object" && v !== null) {
    const entries = Object.entries(v);
    return entries.length === 0 ? "{}" : `{ ${entries.map(([k, x]) => `${key(k)}: ${literal(x)}`).join(", ")} }`;
  }
  return JSON.stringify(v);
}

// An array of objects, one element per line (each must fit the line width; the generator refuses otherwise rather than guess
// Biome's wrapping).
function objectArray(items: readonly unknown[]): string {
  const lines = items.map((x) => {
    const line = `  ${literal(x)},`;
    if (line.length > LINE_WIDTH) throw new Error(`container contract line exceeds ${LINE_WIDTH} columns: ${line}`);
    return line;
  });
  return `[\n${lines.join("\n")}\n]`;
}

export function containerContractText(registry: ConfigRegistry, readerSource: string): string {
  const params = containerParams(registry);
  const defaults = containerDefaults(registry);
  const facts = Object.entries(IMAGE_FACTS).map(([name, v]) => {
    const line = typeof v === "object" ? `export const ${name} = ${literal(v)} as const;` : `export const ${name} = ${literal(v)};`;
    if (line.length > LINE_WIDTH) throw new Error(`container contract line exceeds ${LINE_WIDTH} columns: ${line}`);
    return line;
  });
  const fields = params.map((p) => `  readonly ${key(p.path)}: ${p.kind === "bool" ? "boolean" : "number"};`);
  const defaultLines = Object.entries(defaults).map(([k, v]) => `  ${key(k)}: ${literal(v)},`);
  return [
    "// GENERATED by packages/core/scripts/gen-config.ts from packages/core/src/config (container.ts, container-reader.ts, image-facts.ts",
    "// and the registry). Do not edit: run `pnpm gen:config`. Byte-identical copies ship in every directory listed in core's",
    "// SHIPPED_CONTRACT_COPIES, and a regenerate-and-compare test guards each one.",
    "",
    "// The digest of what this image is built against (delivered keys' bounds, the env name, the cap and the facts). The daemon",
    "// writes its own digest into the document; a mismatch means the image and the daemon are from different revisions.",
    `export const CONTAINER_CONTRACT = ${literal(containerContract(registry))};`,
    `export const CONTAINER_CONFIG_ENV = ${literal(CONTAINER_CONFIG_ENV)};`,
    `export const CONTAINER_CONFIG_MAX_BYTES = ${literal(CONTAINER_CONFIG_MAX_BYTES)};`,
    "",
    "// Image facts (core image-facts.ts and template.ts).",
    ...facts,
    "",
    "// The resolved values a container receives, by registry path.",
    "export interface ContainerConfig {",
    ...fields,
    "}",
    "",
    `export const CONTAINER_PARAMS: readonly ContainerParamSpec[] = ${objectArray(params)};`,
    "",
    "// The registry defaults of the delivered keys: used only when the document is absent and not required.",
    "export const CONTAINER_DEFAULTS: ContainerConfig = Object.freeze({",
    ...defaultLines,
    "});",
    "",
    "export const CONTAINER_READ_SPEC: ContainerReadSpec = {",
    "  contract: CONTAINER_CONTRACT,",
    "  env: CONTAINER_CONFIG_ENV,",
    "  maxBytes: CONTAINER_CONFIG_MAX_BYTES,",
    "  params: CONTAINER_PARAMS,",
    "  defaults: CONTAINER_DEFAULTS as unknown as Readonly<Record<string, number | boolean>>,",
    "};",
    "",
    "// The validated, frozen container config from this process's env. Throws ContainerConfigError (see readContainerDoc).",
    "export const readContainerConfig = (env: Readonly<Record<string, string | undefined>>, opts: ContainerReadOptions): ContainerConfig =>",
    "  readContainerDoc(env[CONTAINER_CONFIG_ENV], CONTAINER_READ_SPEC, opts) as unknown as ContainerConfig;",
    "",
    "// --- the reader, verbatim from packages/core/src/config/container-reader.ts ---",
    "",
    readerSource.trimEnd(),
    "",
  ].join("\n");
}
